//----------------------------------------------------------------------------

module signed_add_with_saturation
(
  input  [3:0] a, b,
  output [3:0] sum
);

  logic [3:0] temp_sum;
  assign temp_sum = a + b;

  assign sum = ((temp_sum[3] != a[3]) & (a[3] == b[3]))
             ? (a[3] ? 4'b1000 : 4'b0111)
             : temp_sum;

endmodule
