module xor_gate_using_mux
(
    input  a,
    input  b,
    output o
);

  logic n;

  mux not_
  (
    .d0 (1'b1),
    .d1 (1'b0),
    .sel (b),
    .y (n)
  );

  mux xor_
  (
    .d0 (b),
    .d1 (n),
    .sel (a),
    .y (o)
  );

endmodule
